"""Every table, imported so Alembic can see them.

``alembic/env.py`` diffs the database against ``Base.metadata``, and a model
that is never imported is invisible to it — which shows up as an autogenerated
migration that *drops* a table. So this package's only job is to be imported,
and every model is re-exported here.

Seven tables, and no more than seven (HAD-3): OAuth state, the encrypted
upstream sessions, and the two audit logs. Fanmoot's own schema is reached over
its public API and is not represented here at all (HAD-1) — there is no ``User``
model in this repo, and a fan appears only as the id and handle on a grant.
"""

