"""The migration and the models do not drift (`S4-1`).

The migration was written by hand rather than autogenerated — the first
migration of a new service has no database to diff against — so "does it match
the models?" is a question nobody can answer by reading a diff. This answers it
by running the migration and comparing the schema it produced with
``Base.metadata``.

It is the check that matters most in this repo for a boring reason: Alembic's
autogenerate diffs against ``Base.metadata``, so the *next* migration written
here inherits whatever disagreement this one left behind, usually as a DROP.
"""

from __future__ import annotations

import importlib.util
from pathlib import Path
from typing import Any

from alembic.operations import Operations
from alembic.runtime.migration import MigrationContext
from sqlalchemy import create_engine, inspect

from app.db import Base

MIGRATIONS = Path(__file__).resolve().parent.parent / "alembic" / "versions"


def _apply_migrations() -> dict[str, set[str]]:
    """Run every migration against a throwaway SQLite database, and reflect it.

    SQLite rather than PostgreSQL for the same reason the rest of the suite uses
    it: no database service in CI. What is being compared is table and column
    *names*, which are dialect-independent — the types and the indexes are not,
    and are deliberately not asserted here.
    """
    engine = create_engine("sqlite://")
    with engine.connect() as connection:
        context = MigrationContext.configure(connection)
        with Operations.context(context):
            for path in sorted(MIGRATIONS.glob("*.py")):
                spec = importlib.util.spec_from_file_location(path.stem, path)
                assert spec is not None and spec.loader is not None
                module = importlib.util.module_from_spec(spec)
                spec.loader.exec_module(module)
                module.upgrade()
        connection.commit()
        inspector = inspect(connection)
        return {
            table: {column["name"] for column in inspector.get_columns(table)}
            for table in inspector.get_table_names()
        }


def _declared() -> dict[str, set[str]]:
    import app.models  # noqa: F401  — registers every table on Base.metadata

    return {
        table.name: {column.name for column in table.columns}
        for table in Base.metadata.sorted_tables
    }


def test_the_migration_creates_exactly_the_tables_the_models_declare() -> None:
    migrated = _apply_migrations()
    declared = _declared()

    assert set(migrated) == set(declared)


def test_every_column_in_the_models_exists_in_the_migration() -> None:
    migrated = _apply_migrations()
    declared = _declared()

    drift: dict[str, Any] = {}
    for table in sorted(set(declared) & set(migrated)):
        if declared[table] != migrated[table]:
            drift[table] = {
                "in the models only": sorted(declared[table] - migrated[table]),
                "in the migration only": sorted(migrated[table] - declared[table]),
            }

    assert not drift, drift


def test_there_are_seven_tables_and_no_more() -> None:
    """HAD-3, as a check rather than a claim: OAuth state, the encrypted
    upstream sessions, and the two audit logs. Fanmoot's own schema is reached
    over its API and is not represented here at all (HAD-1)."""
    assert set(_declared()) == {
        "oauth_clients",
        "upstream_sessions",
        "access_grants",
        "authorization_codes",
        "refresh_tokens",
        "consent_events",
        "tool_calls",
    }


def test_every_credential_column_is_a_hash_or_a_ciphertext() -> None:
    """`S4-1`'s promise, mechanically. A column whose name says it holds a token
    has to be a ``_hash`` — the single exception being the fan's upstream
    refresh token, which cannot be hashed because it has to be *used*, and is
    Fernet ciphertext instead (HAD-3)."""
    import app.models  # noqa: F401

    offenders = []
    for table in Base.metadata.sorted_tables:
        for column in table.columns:
            name = column.name
            holds_credential = any(word in name for word in ("token", "secret", "code", "password"))
            safe = name.endswith(("_hash", "_encrypted", "_expires_at")) or name in {
                # Not credentials: a challenge is a public commitment, an
                # expiry is a timestamp, a method names an algorithm, a country
                # code is a country.
                "code_challenge",
                "code_challenge_method",
                "country_code",
                "grant_types",
                "response_types",
                "token_endpoint_auth_method",
            }
            if holds_credential and not safe:
                offenders.append(f"{table.name}.{name}")

    assert not offenders, f"credential columns that are neither hashed nor encrypted: {offenders}"
