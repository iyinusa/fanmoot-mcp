"""Alembic environment.

The database URL comes from ``FMCP_DATABASE_URL`` via ``app.settings`` rather
than from ``alembic.ini``, so migrations and the application can never point at
different databases — and so production credentials stay in the environment
instead of a committed file.

This database holds OAuth state only (HAD-3). It never sees Fanmoot's schema,
and no migration here has anything to say about Fanmoot's tables.

``app.models`` is imported for its side effect: autogenerate diffs the database
against ``Base.metadata``, and a model that is not imported is invisible to it.
A missing import here shows up as an autogenerated migration that drops a
table. The package arrives with ``S4``; until then the import is guarded, so
``alembic upgrade head`` is a clean no-op rather than an ImportError on every
container start.
"""

from __future__ import annotations

import asyncio
import contextlib
from logging.config import fileConfig

from sqlalchemy import pool
from sqlalchemy.engine import Connection
from sqlalchemy.ext.asyncio import async_engine_from_config

from alembic import context
from app.db import Base
from app.settings import get_settings

with contextlib.suppress(ImportError):  # the guard disappears with S4
    from app import models  # noqa: F401  — registers every table on Base.metadata

config = context.config
if config.config_file_name is not None:
    fileConfig(config.config_file_name)

settings = get_settings()
config.set_main_option("sqlalchemy.url", settings.database_url)

target_metadata = Base.metadata


def _configure(**kwargs: object) -> None:
    context.configure(
        target_metadata=target_metadata,
        # Detect column type changes; without this a widened String stays
        # silently narrow in the database.
        compare_type=True,
        compare_server_default=True,
        **kwargs,  # type: ignore[arg-type]
    )


def run_migrations_offline() -> None:
    _configure(
        url=config.get_main_option("sqlalchemy.url"),
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )
    with context.begin_transaction():
        context.run_migrations()


def do_run_migrations(connection: Connection) -> None:
    _configure(connection=connection)
    with context.begin_transaction():
        context.run_migrations()


async def run_async_migrations() -> None:
    connectable = async_engine_from_config(
        config.get_section(config.config_ini_section, {}),
        prefix="sqlalchemy.",
        poolclass=pool.NullPool,
    )
    async with connectable.connect() as connection:
        await connection.run_sync(do_run_migrations)
    await connectable.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    asyncio.run(run_async_migrations())
